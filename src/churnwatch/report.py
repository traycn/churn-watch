def write_outputs(scored: list[dict], out_dir: Path, *, source: str, model: str, prompt: str | None,
                  call_list_size: int = 10) -> tuple[Path, Path]:
    """scored: [{rec, a (Assessment|None), error, bad (set of 'field=value' strings)}]"""
    out_dir.mkdir(parents=True, exist_ok=True)
    ok = [s for s in scored if s["a"]]
    ranked = sorted(ok, key=lambda s: (-s["a"].risk_score, s["rec"]["days_to_renewal"]))
    at_risk = [s for s in ranked if s["a"].at_risk]

    csv_path = out_dir / "scores.csv"
    with csv_path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["rank", "account_id", "account_name", "at_risk", "risk_score", "main_reason",
                    "reasons", "next_step", "arr_usd", "days_to_renewal", "evidence_unverified", "error"])
        for i, s in enumerate(ranked, 1):
            a = s["a"]
            w.writerow([i, a.account_id, s["rec"]["account_name"], a.at_risk, a.risk_score, a.main_reason,
                        " | ".join(d.explanation for d in a.drivers), a.next_step, s["rec"]["arr_usd"],
                        s["rec"]["days_to_renewal"], len(s["bad"]), ""])
        for s in scored:
            if not s["a"]:
                w.writerow(["", s["rec"]["account_id"], s["rec"]["account_name"], "", "", "", "", "",
                            s["rec"]["arr_usd"], s["rec"]["days_to_renewal"], "", s["error"]])

    html_path = out_dir / "report.html"
    html_path.write_text(TEMPLATE.render(
        today=date.today().isoformat(), source=source, model=model, prompt=prompt,
        total=len(scored), at_risk=at_risk, call_list=at_risk[:call_list_size],
        rest=at_risk[call_list_size:], arr_at_risk=sum(s["rec"]["arr_usd"] for s in at_risk),
        ungrounded=sum(1 for s in ok if s["bad"]),
    ))
    return csv_path, html_path
